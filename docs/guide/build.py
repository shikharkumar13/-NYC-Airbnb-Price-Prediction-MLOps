"""Build airbnb_mlops_guide.md from the chapter files in this folder.

Code blocks in the guide are never typed by hand: a marker line in a chapter
file is replaced with the real contents of that repo file, so the guide can't
drift from the code.

    python docs/guide/build.py            # regenerate airbnb_mlops_guide.md
    python docs/guide/build.py --check    # exit 1 if it's out of date (used by CI)

Marker syntax (on its own line in a chapter file):
    <<<FILE:path>>>                       the whole file
    <<<FILE:path|until:LINE-PREFIX>>>     from the top, stopping before the first line starting with LINE-PREFIX
    <<<FILE:path|from:LINE-PREFIX>>>      from the first line starting with LINE-PREFIX to the end
    ...|title:append                      heading says "Append to" instead of "File"
Decorator lines (@...) directly above a matched line stay with it.
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parent.parent
OUT = REPO / "airbnb_mlops_guide.md"
HEADER = "<!-- Generated by docs/guide/build.py from docs/guide/*.md: edit those, not this file. -->\n"
LANG = {".py": "python", ".yml": "yaml", ".yaml": "yaml", ".ini": "ini", ".txt": "text", ".toml": "toml"}
MARKER = re.compile(r"^<<<FILE:(?P<spec>[^>]+)>>>$", re.M)


def lang_for(path: str) -> str:
    name = pathlib.Path(path).name
    if name == "Dockerfile":
        return "dockerfile"
    if name.startswith("."):
        return "text"
    return LANG.get(pathlib.Path(path).suffix, "text")


def slice_file(path: str, opts: dict) -> str:
    lines = (REPO / path).read_text().splitlines(keepends=True)

    def find(prefix):
        matches = [i for i, line in enumerate(lines) if line.startswith(prefix)]
        if not matches:
            sys.exit(f"build.py: no line starting with {prefix!r} in {path} (update the marker)")
        i = matches[0]
        while i > 0 and lines[i - 1].startswith("@"):  # keep decorators with their function
            i -= 1
        return i

    start = find(opts["from"]) if "from" in opts else 0
    end = find(opts["until"]) if "until" in opts else len(lines)
    return "".join(lines[start:end]).rstrip("\n")


def render(match: re.Match) -> str:
    path, *raw_opts = match.group("spec").split("|")
    opts = dict(o.split(":", 1) for o in raw_opts)
    if not (REPO / path).is_file():
        sys.exit(f"build.py: {path} does not exist (update the marker)")
    verb = "Append to" if opts.get("title") == "append" else "File"
    return f"📄 **{verb}: `{path}`**\n\n```{lang_for(path)}\n{slice_file(path, opts)}\n```"


def build() -> str:
    parts = sorted(HERE.glob("[0-9][0-9]_*.md"))
    text = "\n\n".join(p.read_text().strip("\n") for p in parts) + "\n"
    return HEADER + MARKER.sub(render, text)


if __name__ == "__main__":
    guide = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != guide:
            sys.exit(
                f"{OUT.name} is out of date with the code or docs/guide/.\n"
                "Run: python docs/guide/build.py   and commit the result."
            )
        print(f"{OUT.name} is up to date")
    else:
        OUT.write_text(guide)
        print(f"wrote {OUT.name}: {len(guide.splitlines())} lines")
